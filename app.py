def norm(s):
    s = unicodedata.normalize("NFKD", (s or "").lower())
    s = "".join(c for c in s if not unicodedata.combining(c))
    return s.replace("e-mail", "email")

SUF = sorted("""amentos imentos amento imento adoras adores adora ador acoes acao ucoes ucao idades idade mente ando endo indo
ados adas ado ada idos idas ido ida ante avel ivel ismo ista oso osa ar er ir as es os a e o s""".split(), key=len, reverse=True)

def stem(w):
    for s in SUF:
        if w.endswith(s) and len(w) - len(s) >= 3: return w[:-len(s)]
    return w

def tokens(text):
    return [t for t in re.findall(r"[a-z0-9]+", norm(text)) if t not in STOP and (len(t) > 1 or t.isdigit())]

# grupos de termos relacionados: quem digita um deles também encontra os módulos dos outros (peso menor)
