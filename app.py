REL = {}
for i, grp in enumerate(GRUPOS):
    for w in grp: REL.setdefault(stem(w), set()).add(i)

def extrair(texto):
    """Palavras-chave do texto: sem stopwords, sem repetição, na ordem em que aparecem."""
    vistos, out = set(), []
    for t in tokens(texto):
        r = stem(t)
        if r not in vistos: vistos.add(r); out.append({"termo": t, "raiz": r})
    return out

def casa(raiz, toks):
    if raiz in toks: return 1.0
    if len(raiz) >= 4 and any(t.startswith(raiz) or (len(t) >= 4 and raiz.startswith(t)) for t in toks): return .7
    return 0

def buscar(texto, linhas, limite=30):
    kws = extrair(texto)
    if not kws: return kws, [], []
    raizes = {k["raiz"] for k in kws}
    rel = {}
    for k in kws:
        for gi in REL.get(k["raiz"], ()):
            for w in GRUPOS[gi]:
                if stem(w) not in raizes: rel.setdefault(stem(w), w)
    termos = [(k["raiz"], k["termo"], 1.0) for k in kws] + [(r, w, .35) for r, w in rel.items()]
    docs = []
    for l in linhas:
        docs.append((l, [(p, set(map(stem, tokens(l[c])))) for c, p in
                         (("nome", 3), ("categoria", 2), ("tecnologia", 2), ("descricao", 1))]))
    n = len(docs)
    df = {r: sum(1 for _, cs in docs if any(casa(r, t) for _, t in cs)) for r, _, _ in termos}
    res = []
    for l, cs in docs:
        score, achados = 0, []
        for r, rotulo, peso in termos:
            m = max((p * casa(r, t) for p, t in cs), default=0)
            if m: score += peso * m * math.log(1 + n / (1 + df[r])); achados.append({"termo": rotulo, "relacionado": peso < 1})
        if score: res.append((score, l, achados))
    res.sort(key=lambda x: -x[0])
    topo = res[0][0] if res else 1
    out = [{**dict(l), "relevancia": round(100 * s / topo), "encontrados": a} for s, l, a in res[:limite]]
    return kws, sorted(rel.values()), out

