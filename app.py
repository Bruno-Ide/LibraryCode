def sessao(): return "", 204

@app.get("/api/categorias")
def categorias():
    return jsonify(run("SELECT c.id, c.nome, COUNT(m.id) AS total FROM categorias c LEFT JOIN modulos m ON m.id_categoria=c.id GROUP BY c.id, c.nome ORDER BY c.id"))

@app.get("/api/usuarios")
def usuarios(): return jsonify(run("SELECT * FROM usuarios ORDER BY id"))

@app.get("/api/modulos")
def modulos():
    cat = request.args.get("categoria_id", type=int)
    return jsonify(run(SELECT + (" WHERE m.id_categoria=?" if cat else "") + " ORDER BY LOWER(m.nome)", (cat,) if cat else ()))

@app.get("/api/modulos/<int:mid>")
def modulo(mid):
    r = run(SELECT + " WHERE m.id=?", (mid,))
    return (jsonify(r[0]), 200) if r else (jsonify(erro="Módulo não encontrado."), 404)

def validar(d):
    d = {c: (d.get(c).strip() if isinstance(d.get(c), str) else d.get(c)) or None for c in CAMPOS}
    d["status"] = d["status"] or "Ativo"
    for c in ("nome", "descricao", "id_categoria"):
        if not d[c]: return None, f"O campo '{c}' é obrigatório."
    if not run("SELECT 1 FROM categorias WHERE id=?", (d["id_categoria"],)): return None, "Categoria inexistente."
    for c in ("link", "documentacao"):
        if d[c] and not re.match(r"https?://", d[c]): return None, f"'{c}' deve começar com http:// ou https://"
    return d, None

@app.route("/api/modulos", methods=["POST"])
@app.route("/api/modulos/<int:mid>", methods=["PUT"])
def salvar(mid=None):
    d, erro = validar(request.get_json(silent=True) or {})
    if erro: return jsonify(erro=erro), 400
    novo = mid is None
    if novo:
        mid = run(f"INSERT INTO modulos({','.join(CAMPOS)}) VALUES({','.join('?'*len(CAMPOS))}) RETURNING id", [d[c] for c in CAMPOS], commit=True)[0]["id"]
    else:
        if not run("SELECT 1 FROM modulos WHERE id=?", (mid,)): return jsonify(erro="Módulo não encontrado."), 404
        run(f"UPDATE modulos SET {','.join(c+'=?' for c in CAMPOS)} WHERE id=?", [d[c] for c in CAMPOS] + [mid], commit=True)
    return jsonify(run(SELECT + " WHERE m.id=?", (mid,))[0]), 201 if novo else 200

@app.delete("/api/modulos/<int:mid>")
def apagar(mid):
    run("DELETE FROM modulos WHERE id=?", (mid,), commit=True)
    return "", 204

@app.post("/api/busca")
def busca():
    corpo = request.get_json(silent=True) or {}
    cat = corpo.get("categoria_id")
    linhas = run(SELECT + (" WHERE m.id_categoria=?" if cat else ""), (cat,) if cat else ())
    kws, relacionadas, resultados = buscar(corpo.get("texto", ""), linhas)
    return jsonify(palavras_chave=[k["termo"] for k in kws], relacionadas=relacionadas, total=len(resultados), resultados=resultados)

