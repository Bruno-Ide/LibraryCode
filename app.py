# ---------------------------------------------------------------- banco
# Com DATABASE_URL definida usa Postgres (produção); sem ela, usa SQLite local (desenvolvimento).
URL = os.environ.get("DATABASE_URL")
PG = bool(URL)
TOKEN = os.environ.get("ADMIN_TOKEN")  # se definido, só quem tem o token edita o catálogo
if PG:
    import psycopg
    from psycopg.rows import dict_row

ID_MOD = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if PG else "INTEGER PRIMARY KEY AUTOINCREMENT"
SCHEMA = f"""
CREATE TABLE IF NOT EXISTS categorias(id INTEGER PRIMARY KEY, nome TEXT NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS usuarios(id INTEGER PRIMARY KEY, profissional TEXT, usuario TEXT, cargo TEXT);
CREATE TABLE IF NOT EXISTS modulos(id {ID_MOD}, nome TEXT NOT NULL, descricao TEXT NOT NULL,
  id_categoria INTEGER NOT NULL REFERENCES categorias(id), tecnologia TEXT, versao TEXT,
  status TEXT NOT NULL DEFAULT 'Ativo', link TEXT, documentacao TEXT, id_usuario INTEGER REFERENCES usuarios(id))"""
SELECT = """SELECT m.*, c.nome AS categoria, u.profissional AS criado_por FROM modulos m
  JOIN categorias c ON c.id = m.id_categoria LEFT JOIN usuarios u ON u.id = m.id_usuario"""

def conn():
    if "db" not in g:
        if PG: g.db = psycopg.connect(URL, row_factory=dict_row)
        else:
            g.db = sqlite3.connect(DB); g.db.row_factory = sqlite3.Row
    return g.db

def run(sql, args=(), commit=False):
    """Executa SQL (escrito com ?) e devolve lista de dicts."""
    cur = conn().execute(sql.replace("?", "%s") if PG else sql, args)
    rows = [dict(r) for r in cur.fetchall()] if cur.description else []
    if commit: conn().commit()
    return rows

@app.teardown_appcontext
def close_db(_):
    if (c := g.pop("db", None)): c.close()

def init_db():
    """Cria as tabelas e, se o banco estiver vazio, carrega o seed.json."""
    with app.app_context():
        for stmt in SCHEMA.split(";"): run(stmt)
        if run("SELECT COUNT(*) AS n FROM categorias")[0]["n"] == 0:
            seed = json.loads((BASE / "seed.json").read_text(encoding="utf-8"))
            for t, cols in (("categorias", ("id", "nome")), ("usuarios", ("id", "profissional", "usuario", "cargo")),
                            ("modulos", ("id",) + CAMPOS)):
                for r in seed[t]:
                    run(f"INSERT INTO {t}({','.join(cols)}) VALUES({','.join('?'*len(cols))}) ON CONFLICT DO NOTHING", [r[c] for c in cols])
            if PG: run("SELECT setval(pg_get_serial_sequence('modulos','id'), (SELECT MAX(id) FROM modulos))")
        conn().commit()

@app.before_request
def proteger():
    """Leitura e busca são públicas; criar/editar/excluir exigem o ADMIN_TOKEN (quando definido)."""
    if TOKEN and request.method in ("POST", "PUT", "DELETE") and request.path != "/api/busca":
        enviado = request.headers.get("Authorization", "").encode()
        if not hmac.compare_digest(enviado, f"Bearer {TOKEN}".encode()):
            return jsonify(erro="Acesso restrito a editores."), 401

